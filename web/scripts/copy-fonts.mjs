// Copies the self-hosted fonts (latin subset woff2 files) and their SIL Open
// Font License texts from the @fontsource packages into src/fonts, and writes
// src/fonts/fonts.css. Run once after changing the list: npm run fonts.
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src", "fonts");
const LATIN =
  "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329," +
  "U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";

// [package, css family, folder, [[file stem, weight, style, stretch?], ...]]
const FONTS = [
  ["@fontsource/unbounded", "Unbounded", "unbounded", [["unbounded-latin-600-normal", 600, "normal"], ["unbounded-latin-700-normal", 700, "normal"]]],
  ["@fontsource/atkinson-hyperlegible", "Atkinson Hyperlegible", "atkinson-hyperlegible", [
    ["atkinson-hyperlegible-latin-400-normal", 400, "normal"], ["atkinson-hyperlegible-latin-700-normal", 700, "normal"]]],
  ["@fontsource/vt323", "VT323", "vt323", [["vt323-latin-400-normal", 400, "normal"]]],
  ["@fontsource/barlow", "Barlow", "barlow", [["barlow-latin-500-normal", 500, "normal"], ["barlow-latin-700-normal", 700, "normal"]]],
  ["@fontsource/barlow-condensed", "Barlow Condensed", "barlow-condensed", [
    ["barlow-condensed-latin-700-italic", 700, "italic"], ["barlow-condensed-latin-800-italic", 800, "italic"],
    ["barlow-condensed-latin-900-italic", 900, "italic"]]],
  ["@fontsource-variable/archivo", "Archivo", "archivo", [["archivo-latin-standard-normal", "100 900", "normal", "62% 125%"]]],
];

let css = "/* Generated by scripts/copy-fonts.mjs. All families are under the SIL Open Font License 1.1. */\n";
for (const [pkg, family, folder, faces] of FONTS) {
  const src = join(root, "node_modules", pkg);
  const dest = join(out, folder);
  mkdirSync(dest, { recursive: true });
  copyFileSync(join(src, "LICENSE"), join(dest, "OFL.txt"));
  for (const [stem, weight, style, stretch] of faces) {
    copyFileSync(join(src, "files", `${stem}.woff2`), join(dest, `${stem}.woff2`));
    css += `@font-face {\n  font-family: "${family}";\n  font-style: ${style};\n  font-weight: ${weight};\n` +
      (stretch ? `  font-stretch: ${stretch};\n` : "") +
      `  font-display: block;\n  src: url("./${folder}/${stem}.woff2") format("woff2");\n  unicode-range: ${LATIN};\n}\n`;
  }
}
writeFileSync(join(out, "fonts.css"), css);
console.log(`fonts copied to ${out}`);
